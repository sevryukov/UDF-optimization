-- {Текст задания}

USE udf_optimization;
GO

CHECKPOINT;
DBCC DROPCLEANBUFFERS;
DBCC FREEPROCCACHE;
GO

SET STATISTICS TIME ON;
SET STATISTICS IO ON;

DECLARE @StartTime DATETIME2 = SYSUTCDATETIME();
SELECT COUNT(*) FROM dbo.F_WORKS_LIST() WHERE ID_WORK <= 3000;
DECLARE @EndTime DATETIME2 = SYSUTCDATETIME();
PRINT 'Elapsed time (DMV): ' + CAST(DATEDIFF(MILLISECOND, @StartTime, @EndTime) AS VARCHAR) + ' ms';
GO

SET SHOWPLAN_XML ON;
GO
SELECT * FROM dbo.F_WORKS_LIST() WHERE ID_WORK <= 3000;
GO
SET SHOWPLAN_XML OFF;
GO